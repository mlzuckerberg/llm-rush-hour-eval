#!/usr/bin/env python3
"""
Aggregate Protocol A (run_eval) JSON by optimal_moves bin: first-move legal rate
and mean applied prefix. Emits Markdown + LaTeX tabular rows for the paper.

Usage:
  PYTHONPATH=. python scripts/pa_bin_comparison.py \\
    evaluation_outputs/openai_levels_eval.json evaluation_outputs/gpt4o_levels_eval.json \\
    --latex paper/generated_pa_bin_table.tex

  # Optional columns (in order): \\texttt{gpt-5.4-mini}, \\texttt{gpt-5.4}, between mini and \\texttt{gpt-4o}
  PYTHONPATH=. python scripts/pa_bin_comparison.py \\
    evaluation_outputs/openai_levels_eval.json evaluation_outputs/gpt4o_levels_eval.json \\
    --gpt54mini-json evaluation_outputs/gpt54mini_levels_eval.json \\
    --gpt54-json evaluation_outputs/gpt54_levels_eval.json \\
    --latex paper/generated_pa_bin_table.tex
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, DefaultDict, Dict, List, Tuple

Agg = Dict[str, Tuple[int, int, float, float]]

# bin name
def _bin_name(opt: int) -> str:
    if opt <= 42:
        return "38--42"
    if opt <= 47:
        return "43--47"
    if opt <= 52:
        return "48--52"
    return "53--60"


# load rows
def _load_rows(path: Path) -> List[Dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return list(data.get("per_level", []))


# aggregate
def _aggregate(rows: List[Dict[str, Any]]) -> Agg:
    """Per stratification bin: ``(n, first_ok_count, first_ok_rate, mean_applied)``."""
    acc: DefaultDict[str, List[int]] = defaultdict(list)
    for r in rows:
        o = r.get("optimal_moves")
        if o is None:
            continue
        b = _bin_name(int(o))
        acc[b].append(int(r.get("applied") or 0))
    out: Agg = {}
    for b, apps in sorted(acc.items()):
        n = len(apps)
        ok = sum(1 for a in apps if a >= 1)
        out[b] = (n, ok, ok / n if n else 0.0, sum(apps) / n if n else 0.0)
    return out


def _latex_shortstack_label(tex_name: str) -> str:
    """tex_name like 'mini' or '\\texttt{gpt-5.4-mini}'."""
    return f"\\shortstack{{{tex_name}\\\\first-move}} & \\shortstack{{{tex_name}\\\\mean pref.}}"


def main() -> None:
    """CLI: compare Protocol A JSONs by ``optimal_moves`` bin; emit MD/LaTeX."""
    ap = argparse.ArgumentParser()
    ap.add_argument("mini_json", type=Path)
    ap.add_argument("gpt4o_json", type=Path)
    ap.add_argument(
        "--gpt54mini-json",
        type=Path,
        default=None,
        metavar="PATH",
        help="Optional Protocol A JSON (gpt-5.4-mini).",
    )
    ap.add_argument(
        "--gpt54-json",
        type=Path,
        default=None,
        metavar="PATH",
        help="Optional Protocol A JSON (gpt-5.4 full).",
    )
    ap.add_argument("--markdown", type=Path, default=None)
    ap.add_argument("--latex", type=Path, default=None)
    args = ap.parse_args()

    a = _aggregate(_load_rows(args.mini_json))
    b = _aggregate(_load_rows(args.gpt4o_json))
    c = _aggregate(_load_rows(args.gpt54mini_json)) if args.gpt54mini_json else None
    d = _aggregate(_load_rows(args.gpt54_json)) if args.gpt54_json else None

    # Order: mini → optional 5.4-mini → optional 5.4 → gpt-4o
    models: List[Tuple[str, str, Agg]] = [
        ("mini", "mini", a),
    ]
    if c:
        models.append(("gpt-5.4-mini", "\\texttt{gpt-5.4-mini}", c))
    if d:
        models.append(("gpt-5.4", "\\texttt{gpt-5.4}", d))
    models.append(("gpt-4o", "\\texttt{gpt-4o}", b))

    bins_set: set[str] = set()
    for _name, _tex, agg in models:
        bins_set |= set(agg.keys())
    bins = sorted(bins_set)

    # Markdown
    ncol_md = 2 + 2 * len(models)
    md: list[str] = ["# Protocol A bin breakdown (from stored JSON)\n"]
    hdr = "| Bin | n |"
    for slug, _tex, _agg in models:
        hdr += f" {slug} first-move | {slug} mean prefix |"
    md.append(hdr + "\n")
    md.append("| " + " | ".join(["---"] * ncol_md) + " |\n")

    for bn in bins:
        parts = [bn]
        nmax = 0
        row_vals: List[Tuple[float, float]] = []
        for _slug, _tex, agg in models:
            _nx, _okx, rx, mx = agg.get(bn, (0, 0, 0.0, 0.0))
            nmax = max(nmax, _nx)
            row_vals.append((rx, mx))
        parts.append(str(nmax))
        for rx, mx in row_vals:
            parts.append(f"{rx:.3f}")
            parts.append(f"{mx:.3f}")
        md.append("| " + " | ".join(parts) + " |\n")

    # LaTeX
    ncol = 2 + 2 * len(models)  # Bin, n, + 2 per model
    col_spec = "l" + "c" * (ncol - 1)
    latex_lines = [
        "% Auto-generated by scripts/pa_bin_comparison.py — do not hand-edit.\n",
        f"\\begin{{tabular}}{{{col_spec}}}\n",
        "\\toprule\n",
        "Bin ($\\texttt{optimal\\_moves}$) & $n$ & ",
    ]
    header_parts: List[str] = []
    for _slug, tex, _agg in models:
        header_parts.append(_latex_shortstack_label(tex))
    latex_lines.append(" & ".join(header_parts) + " \\\\\n")
    latex_lines.append("\\midrule\n")

    for bn in bins:
        cells: List[str] = []
        nmax = 0
        for _slug, _tex, agg in models:
            nx, _ok, rx, mx = agg.get(bn, (0, 0, 0.0, 0.0))
            nmax = max(nmax, nx)
            cells.extend([f"{rx:.3f}", f"{mx:.3f}"])
        latex_lines.append(f"{bn} & {nmax} & " + " & ".join(cells) + " \\\\\n")

    latex_lines.append("\\bottomrule\n")
    latex_lines.append("\\end{tabular}\n")

    text = "".join(md)
    print(text)
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(text, encoding="utf-8")
        print(f"Wrote {args.markdown}")
    if args.latex:
        args.latex.parent.mkdir(parents=True, exist_ok=True)
        args.latex.write_text("".join(latex_lines), encoding="utf-8")
        print(f"Wrote {args.latex}")


if __name__ == "__main__":
    main()
